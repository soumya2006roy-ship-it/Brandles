"""Generate small, original BrandLens visual compliance fixtures."""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont


OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "visual"
APPROVED_GREEN = "#173F35"
APPROVED_CORAL = "#F07F60"


def poster(background: str, *, logo: str = APPROVED_CORAL, disclaimer: bool = True) -> Image.Image:
    image = Image.new("RGB", (720, 480), background)
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((36, 32, 684, 448), radius=24, outline="#FFFFFF", width=5)
    draw.ellipse((70, 70, 160, 160), fill=logo)
    draw.text((190, 78), "WINTER GLOW", fill="#FFFFFF", font=ImageFont.load_default(size=38))
    draw.text((72, 220), "Hydration for everyday skin", fill="#FFFFFF", font=ImageFont.load_default(size=30))
    draw.rounded_rectangle((72, 288, 330, 350), radius=14, fill=APPROVED_CORAL)
    draw.text((94, 303), "Explore the range", fill="#14231D", font=ImageFont.load_default(size=24))
    if disclaimer:
        draw.text((72, 400), "Terms apply. See approved offer details.", fill="#FFFFFF", font=ImageFont.load_default(size=18))
    return image


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    cases = {
        "compliant-poster.png": poster(APPROVED_GREEN),
        "wrong-logo.png": poster(APPROVED_GREEN, logo="#385CA8"),
        "off-brand-colours.png": poster("#A52F91", logo="#F4D345"),
        "missing-disclaimer.png": poster(APPROVED_GREEN, disclaimer=False),
        "blurry-low-quality.png": poster(APPROVED_GREEN).resize((72, 48)).resize((720, 480)).filter(ImageFilter.GaussianBlur(5)),
    }
    for filename, image in cases.items():
        image.save(OUT / filename, format="PNG", optimize=True)
    (OUT / "README.md").write_text(
        "# Generated visual fixtures\n\n"
        "These original synthetic images are generated by `python api/scripts/generate_visual_fixtures.py`; "
        "they contain no customer or copyrighted assets. Expected cases: compliant poster, wrong logo, "
        "off-brand colours, missing disclaimer and blurry/low-quality image.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
